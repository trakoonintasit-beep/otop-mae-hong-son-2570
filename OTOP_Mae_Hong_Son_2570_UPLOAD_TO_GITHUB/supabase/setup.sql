-- Requires Supabase Auth users; never store user passwords in product tables.

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) between 1 and 160),
  category text not null,
  district text not null,
  price numeric(12,2) not null default 0 check (price >= 0),
  unit text not null default 'ชิ้น',
  producer text not null,
  shop text not null,
  description text not null default '',
  story text not null default '',
  image text not null default '',
  phone text not null default '',
  line text not null default '',
  facebook text not null default '',
  address text not null default '',
  lat double precision check(lat between -90 and 90),
  lng double precision check(lng between -180 and 180),
  featured boolean not null default false,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_published_idx on public.products(is_published, id);
create index if not exists products_district_idx on public.products(district);

-- Protected helper: viewers cannot modify the admin table through the browser.
create or replace function public.is_otop_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.admins where user_id = (select auth.uid()));
$$;
revoke all on function public.is_otop_admin() from public;
grant execute on function public.is_otop_admin() to anon, authenticated;

alter table public.admins enable row level security;
alter table public.products enable row level security;

drop policy if exists "admins can read own membership" on public.admins;
create policy "admins can read own membership" on public.admins
for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists "visitors can read published products" on public.products;
create policy "visitors can read published products" on public.products
for select to anon, authenticated
using (is_published = true or public.is_otop_admin());

drop policy if exists "admin can insert products" on public.products;
create policy "admin can insert products" on public.products
for insert to authenticated with check (public.is_otop_admin());

drop policy if exists "admin can update products" on public.products;
create policy "admin can update products" on public.products
for update to authenticated using (public.is_otop_admin()) with check (public.is_otop_admin());

drop policy if exists "admin can delete products" on public.products;
create policy "admin can delete products" on public.products
for delete to authenticated using (public.is_otop_admin());

-- Public bucket for product pictures. Do NOT store personal/private images here.
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('product-images','product-images',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public=true, file_size_limit=5242880,
  allowed_mime_types=array['image/jpeg','image/png','image/webp'];

drop policy if exists "admins upload otop images" on storage.objects;
create policy "admins upload otop images" on storage.objects
for insert to authenticated with check (bucket_id='product-images' and public.is_otop_admin());

drop policy if exists "admins update otop images" on storage.objects;
create policy "admins update otop images" on storage.objects
for update to authenticated using (bucket_id='product-images' and public.is_otop_admin())
with check (bucket_id='product-images' and public.is_otop_admin());

drop policy if exists "admins delete otop images" on storage.objects;
create policy "admins delete otop images" on storage.objects
for delete to authenticated using (bucket_id='product-images' and public.is_otop_admin());

